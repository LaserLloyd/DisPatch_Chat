"""Gate G7: the committed contracts equal the ones the code generates.

``docs/contracts/`` (OpenAPI, permissions, routes, errors, capabilities, manifest
schemas) and ``docs/errors.md`` are GENERATED by ``scripts/gen_contracts.py``. If this
fails, you changed the API, a permission, a route's policy or an error and did not
regenerate - run ``python scripts/gen_contracts.py`` and commit the result. A change a
client could notice (``breaking_changes``) also needs a version bump.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "gen_contracts.py"


def _run(*args: str) -> subprocess.CompletedProcess:
    env = {**os.environ, "PYTHONUTF8": "1"}
    for k in ("DISPATCH_DATA_DIR", "LOCAL_CHAT_DATA_DIR"):
        env.pop(k, None)
    return subprocess.run([sys.executable, str(SCRIPT), *args], cwd=ROOT, env=env,
                          capture_output=True, text=True, timeout=240)


def test_committed_contracts_are_current():
    r = _run("--check")
    assert r.returncode == 0, f"contracts are stale:\n{r.stdout[-3000:]}\n{r.stderr[-1500:]}"


def test_contract_files_are_valid_json_with_lf_endings():
    for p in sorted((ROOT / "docs" / "contracts").rglob("*.json")):
        raw = p.read_bytes()
        assert b"\r\n" not in raw, f"{p.name} has CRLF endings"
        json.loads(raw)


def test_the_breaking_change_detector_sees_a_removed_route():
    sys.path.insert(0, str(ROOT / "scripts"))
    try:
        import gen_contracts
    finally:
        sys.path.pop(0)
    old = {"paths": {"/a": {"get": {}}, "/b": {"post": {"parameters": []}}}}
    new = {"paths": {"/b": {"post": {"parameters": [{"name": "x", "required": True}]}}}}
    found = gen_contracts.breaking_changes(old, new)
    assert "removed path /a" in found
    assert any("parameter 'x' became required" in f for f in found)
    assert gen_contracts.breaking_changes(old, old) == []
