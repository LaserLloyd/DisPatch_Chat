def extract_refs(content: str | None, media_url: str | None, metadata: str | None) -> set[str]:
    """Reference keys a message shows: ``<name>`` for each ``/media/<name>`` (the same reading the
    011 backfill uses, ``database.media_names_in``) and ``reaction:<id>`` for a reaction trace."""
    from . import database
    out = set(database.media_names_in(content, media_url, metadata))
    if metadata and "reaction_id" in metadata:
        out.update(f"reaction:{r}" for r in _REACTION_ID_RE.findall(metadata))
    return out


def _txn(con: sqlite3.Connection):
    """One short write transaction (the task's connections are autocommit, so without this a loop
    of single-row writes is one commit per row: slow, and it starves other writers)."""
    return _Txn(con)


class _Txn:
    def __init__(self, con: sqlite3.Connection) -> None:
        self.con = con

    def __enter__(self) -> sqlite3.Connection:
        self.con.execute("BEGIN IMMEDIATE")
        return self.con

    def __exit__(self, exc_type, exc, tb) -> bool:
        self.con.execute("ROLLBACK" if exc_type else "COMMIT")
        return False


def _upsert_refs(con: sqlite3.Connection, refs: dict[str, str]) -> None:
    if not refs:
        return
    con.executemany(
        "INSERT INTO media_refs(name,last_ref_at) VALUES(?,?) "
        "ON CONFLICT(name) DO UPDATE SET last_ref_at=MAX(last_ref_at, excluded.last_ref_at)",
        list(refs.items()))


def scan_refs(con: sqlite3.Connection, *, chunk: int = 5000, sleep: float = 0.0,
              recheck_tail: int = 20000, deadline: float | None = None) -> dict[str, int]:
    """Bring ``media_refs`` up to date from messages added since the stored rowid watermark.

    Also re-reads the newest ``recheck_tail`` rows and the output of image jobs updated since
    the last scan, because an image job rewrites an *older* message when its picture arrives.
    Resumable: the watermark moves after every chunk. A watermark above the table's highest
    rowid (VACUUM can renumber) restarts from zero."""
    mx = con.execute("SELECT COALESCE(MAX(rowid),0) FROM messages").fetchone()[0]
    wm = int(state_get(con, "media_refs.rowid", "0") or 0)
    if wm > mx:
        wm = 0
    scanned = noted = 0
    start = max(0, min(wm, mx - recheck_tail)) if recheck_tail else wm
    pos = start
    while True:
        rows = con.execute(
            "SELECT rowid, created_at, media_url, content, metadata FROM messages "
            "WHERE rowid > ? AND (media_url IS NOT NULL OR instr(content,'/media/') > 0 "
            "OR instr(metadata,'/media/') > 0 OR instr(metadata,'reaction_id') > 0) "
            "ORDER BY rowid LIMIT ?", (pos, chunk)).fetchall()
        if not rows:
            pos = mx
            break
        refs: dict[str, str] = {}
        for _rowid, created, media_url, content, metadata in rows:
            for key in extract_refs(content, media_url, metadata):
                if created and created > refs.get(key, ""):
                    refs[key] = created
        pos = rows[-1][0]
        last_chunk = len(rows) < chunk
        with _txn(con):
            _upsert_refs(con, refs)
            state_set(con, "media_refs.rowid", str(max(wm, mx if last_chunk else pos)))
        noted += len(refs)
        scanned += len(rows)
        if last_chunk:
            pos = max(pos, mx)
            break
        if sleep:
            time.sleep(sleep)
        if deadline and time.monotonic() > deadline:
            return {"scanned": scanned, "refs": noted, "complete": 0}
    state_set(con, "media_refs.rowid", str(max(wm, pos, mx)))     # nothing left to read: one tiny write
    # image jobs rewrite their (older) placeholder message when the picture arrives
    since = state_get(con, "media_refs.jobs_at", "")
    try:
        jobs = con.execute(
            "SELECT j.media_url, COALESCE(m.created_at, j.updated_at), j.updated_at FROM image_jobs j "
            "LEFT JOIN messages m ON m.id = j.message_id "
            "WHERE j.state='done' AND j.media_url IS NOT NULL AND j.updated_at > ?", (since,)).fetchall()
    except sqlite3.OperationalError:
        jobs = []
    if jobs:
        refs = {}
        for url, at, _upd in jobs:
            for key in extract_refs(None, url, None):
                refs[key] = max(at or "", refs.get(key, ""))
        with _txn(con):
            _upsert_refs(con, refs)
            state_set(con, "media_refs.jobs_at", max(j[2] for j in jobs))
    return {"scanned": scanned, "refs": noted, "complete": 1}


def _studio_ledger(data: Path) -> Path:
    return data / "apps-data" / "imagestudio" / "images.jsonl"


def read_studio_ledger(data: Path) -> list[dict]:
    rows: list[dict] = []
    try:
        with _studio_ledger(data).open(encoding="utf-8") as f:
            for line in f:
                with contextlib.suppress(ValueError):
                    row = json.loads(line)
                    if isinstance(row, dict) and row.get("url"):
                        rows.append(row)
    except OSError:
        pass
    return rows


def sync_generated(con: sqlite3.Connection, data: Path) -> int:
    """Record every generated ``/media`` file (finished image jobs, the Image Studio ledger)."""
    try:
        jobs = con.execute("SELECT media_url, updated_at FROM image_jobs "
                           "WHERE state='done' AND media_url IS NOT NULL").fetchall()
    except sqlite3.OperationalError:
        jobs = []
    rows: list[tuple] = []
    for url, at in jobs:
        m = _MEDIA_REF_RE.search(url or "")
        if m:
            rows.append((m.group(1), "chat_pic", at or "", None))
    for row in read_studio_ledger(data):
        m = _MEDIA_REF_RE.search(str(row.get("url") or ""))
        if m:
            rows.append((m.group(1), "imagestudio", str(row.get("created_at") or ""),
                         row.get("owner_profile_id")))
    if not rows:
        return 0
    added = 0
    for chunk in _chunks(rows, 2000):
        with _txn(con):
            before = con.total_changes
            con.executemany("INSERT OR IGNORE INTO generated_media(name,kind,created_at,owner) VALUES(?,?,?,?)", chunk)
            added += con.total_changes - before
    return added


