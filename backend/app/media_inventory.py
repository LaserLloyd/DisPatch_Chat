@dataclass
class ImageAsset:
    path: Path
    kind: str
    created_at: float                     # epoch seconds (file time)
    owner: str | None = None
    refs: tuple[str, ...] = ()            # media_refs keys that show it
    size: int = 0
    name: str = ""                        # the key in media_expired
    rel: str = ""                         # path under the data dir ('/'-separated), for the trash
    protect: str | None = None            # set by plan_expiry when kept
    group: tuple = field(default_factory=tuple)   # sibling files that go with it (avatar pairs)


def _rel(data: Path, p: Path) -> str:
    return p.relative_to(data).as_posix()


def _reaction_ref_keys(mood: str, path: Path) -> tuple[str, ...]:
    try:
        from . import reactions
        ids = {reactions.pool_file_id(mood, path.name), reactions.pool_file_id(mood.lower(), path.name)}
        with contextlib.suppress(Exception):
            ids.add(reactions._disambiguated(mood, path))
            ids.add(reactions._disambiguated(mood.lower(), path))
    except Exception:       # pragma: no cover - reactions import problems must not stop maintenance
        return ()
    return tuple(f"reaction:{i}" for i in sorted(ids))


def iter_reaction_spent(data: Path) -> Iterator[ImageAsset]:
    root = data / "reactions" / "spent"
    for e in _walk_files(root):
        if not _is_image(e.name):
            continue
        p = Path(e.path)
        try:
            st = e.stat(follow_symlinks=False)
        except OSError:
            continue
        mood = p.parent.name
        yield ImageAsset(p, "reaction_spent", st.st_mtime, None, _reaction_ref_keys(mood, p),
                         st.st_size, _rel(data, p), _rel(data, p))


def iter_generated_media(con: sqlite3.Connection, data: Path) -> Iterator[ImageAsset]:
    media = data / "media"
    rows = con.execute("SELECT name, kind, created_at, owner FROM generated_media").fetchall()
    for name, kind, _created_at, owner in rows:
        p = media / name
        try:
            st = p.stat()
        except OSError:
            continue
        if not p.is_file() or not _is_image(name):
            continue
        yield ImageAsset(p, kind if kind in KINDS else "chat_pic", st.st_mtime, owner, (name,),
                         st.st_size, name, _rel(data, p))


def iter_avatar_pool_spent(data: Path) -> Iterator[ImageAsset]:
    root = data / "avatar-pool"
    try:
        bots = [d for d in root.iterdir() if d.is_dir() and not d.name.startswith(".")]
    except OSError:
        return
    for bot in bots:
        for e in _walk_files(bot / "spent"):
            if not _is_image(e.name):
                continue
            p = Path(e.path)
            try:
                st = e.stat(follow_symlinks=False)
            except OSError:
                continue
            yield ImageAsset(p, "avatar_pool_spent", st.st_mtime, None, (), st.st_size,
                             _rel(data, p), _rel(data, p))


def _snapshot_stem(name: str) -> str:
    stem = Path(name).stem
    for suf in ("-full", "-thumb", "-face"):
        if stem.endswith(suf):
            return stem[: -len(suf)]
    return stem


def iter_unreferenced_snapshots(con: sqlite3.Connection, data: Path) -> tuple[list[ImageAsset], int]:
    """Thread avatar snapshots no thread points at, and how many are in use."""
    root = data / "avatar-snapshots"
    try:
        used = {_snapshot_stem(r[0]) for r in con.execute(
            "SELECT DISTINCT avatar_snapshot FROM threads WHERE avatar_snapshot IS NOT NULL AND avatar_snapshot != ''")}
    except sqlite3.OperationalError:
        return [], 0
    out: list[ImageAsset] = []
    in_use = 0
    try:
        entries = [e for e in os.scandir(root) if e.is_file(follow_symlinks=False) and not e.name.startswith(".")]
    except OSError:
        return [], 0
    for e in entries:
        if not _is_image(e.name):
            continue
        if _snapshot_stem(e.name) in used:
            in_use += 1
            continue
        try:
            st = e.stat(follow_symlinks=False)
        except OSError:
            continue
        p = Path(e.path)
        out.append(ImageAsset(p, "avatar_snapshot", st.st_mtime, None, (), st.st_size,
                              _rel(data, p), _rel(data, p)))
    return out, in_use


def _count_files(root: Path, *, images_only: bool = True) -> int:
    n = 0
    for e in _walk_files(root):
        if not images_only or _is_image(e.name):
            n += 1
    return n


def _active_job_names(con: sqlite3.Connection) -> set[str]:
    """``/media`` names a queued or running image job reads (a reference picture)."""
    names: set[str] = set()
    try:
        for (spec,) in con.execute("SELECT spec FROM image_jobs WHERE state IN ('queued','running')"):
            names.update(_MEDIA_REF_RE.findall(spec or ""))
    except sqlite3.OperationalError:
        pass
    return names


def _ref_times(con: sqlite3.Connection, assets: list[ImageAsset]) -> dict[str, float]:
    keys = sorted({k for a in assets for k in a.refs})
    out: dict[str, float] = {}
    for chunk in _chunks(keys, 500):
        for name, at in con.execute(
                f"SELECT name, last_ref_at FROM media_refs WHERE name IN ({_marks(len(chunk))})", chunk):
            out[name] = _epoch(at)
    return out


