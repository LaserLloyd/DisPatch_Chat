"""Every generated-image source, the in-use set, and the expiry plan (BUILD-PLAN-v2 1.13.6).

One place answers three questions for the image-retention rule and the orphan sweep:

* **What images does DisPatch generate?** :data:`WRITERS` lists every code path that writes
  one (found with a sweep over ``image_jobs``, ``image_providers``, ``imagestudio``,
  ``reactions``, ``avatar_pool``, ``avatar_snapshots`` and ``apps/*``), and says which kinds the
  retention rule covers. Each covered writer has one *source* here that yields
  :class:`ImageAsset` rows.
* **Which of them are still in use?** :func:`plan_expiry` never lists a current avatar, the
  unfired reaction shelf, the ready avatar pool, a picture a message newer than the cutoff
  still shows, a picture a queued or running job reads, or anything under ``static/``.
* **What would happen?** :func:`plan_expiry` is the dry run; :func:`execute_expiry` performs
  exactly that plan (a test proves preview == job on the same data). Expired files move to
  ``<data>/trash/images-<date>/<path under the data dir>`` (an instant rename on one
  filesystem) and their name goes into ``media_expired``; :func:`restore_images` puts them
  back, :func:`purge_trash` deletes them after the hold.

Only pictures DisPatch itself recorded as generated are ever expired. A file in ``media/``
that no generator recorded (an upload, a pasted picture, an agent's attachment) is *not* an
asset here and is never touched by the retention rule.

Age basis: an image is aged out when ``max(file time, newest message that shows it)`` is older
than the cutoff, so a picture in an active conversation is not stripped from under it.

Reference keys (table ``media_refs``): a ``/media/<name>`` file is keyed by ``<name>``; a fired
reaction image is keyed ``reaction:<reaction id>``. :func:`scan_refs` keeps the table current
from new messages only (a stored rowid watermark), so the nightly cost follows the day's
messages and not the whole table.
"""

