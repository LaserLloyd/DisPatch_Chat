@dataclass
class Plan:
    mode: str
    months: int | None
    cutoff: float | None
    candidates: list[ImageAsset] = field(default_factory=list)
    protected: dict[str, int] = field(default_factory=dict)

    def summary(self) -> dict:
        by_kind: dict[str, dict[str, int]] = {}
        oldest = newest = None
        for a in self.candidates:
            row = by_kind.setdefault(a.kind, {"count": 0, "bytes": 0})
            row["count"] += 1
            row["bytes"] += a.size
            oldest = a.created_at if oldest is None else min(oldest, a.created_at)
            newest = a.created_at if newest is None else max(newest, a.created_at)
        return {
            "mode": self.mode, "months": self.months,
            "cutoff": _iso(self.cutoff) if self.cutoff else None,
            "would_expire": {
                "count": len(self.candidates), "bytes": sum(a.size for a in self.candidates),
                "by_kind": by_kind},
            "protected": dict(sorted(self.protected.items())),
            "oldest": _iso(oldest) if oldest else None,
            "newest": _iso(newest) if newest else None,
        }


def plan_expiry(con: sqlite3.Connection, data_dir: Path | str | None, mode: str, months: int | None,
                now: datetime | None = None) -> Plan:
    """What the image rule would expire right now. Read-only apart from keeping the reference
    index current (``media_refs``) and the generated-media record. ``forever`` plans nothing."""
    data = _data(data_dir)
    now = now or datetime.now(UTC)
    if mode != "months" or not months:
        return Plan("forever", None, None)
    cutoff = months_ago(now, int(months)).timestamp()
    plan = Plan("months", int(months), cutoff)
    prot = plan.protected

    ensure_schema(con)
    scan_refs(con)
    sync_generated(con, data)
    assets: list[ImageAsset] = []
    assets.extend(iter_reaction_spent(data))
    assets.extend(iter_generated_media(con, data))
    assets.extend(iter_avatar_pool_spent(data))
    snaps, snap_in_use = iter_unreferenced_snapshots(con, data)
    assets.extend(snaps)
    already = {r[0] for r in con.execute("SELECT name FROM media_expired")}
    active = _active_job_names(con)
    times = _ref_times(con, assets)

    for a in assets:
        if a.name in already or a.created_at >= cutoff:
            continue
        ref = max((times.get(k, 0.0) for k in a.refs), default=0.0)
        if ref >= cutoff:
            prot[PROTECT_REFERENCED] = prot.get(PROTECT_REFERENCED, 0) + 1
            a.protect = PROTECT_REFERENCED
            continue
        if a.kind != "reaction_spent" and a.path.name in active:
            prot[PROTECT_ACTIVE_JOB] = prot.get(PROTECT_ACTIVE_JOB, 0) + 1
            a.protect = PROTECT_ACTIVE_JOB
            continue
        plan.candidates.append(a)

    # the in-use sets that are never even considered: counted so the card can say so
    shelf = sum(_count_files(d) for d in sorted((data / "reactions").glob("moods*")) if d.is_dir()) \
        if (data / "reactions").is_dir() else 0
    ready = sum(_count_files(d / "ready") for d in (data / "avatar-pool").iterdir()
                if d.is_dir() and not d.name.startswith(".")) if (data / "avatar-pool").is_dir() else 0
    avatars = _count_files(data / "avatars")
    for key, n in ((PROTECT_SHELF, shelf), (PROTECT_POOL_READY, ready), (PROTECT_AVATARS, avatars),
                   (PROTECT_SNAPSHOT, snap_in_use)):
        if n:
            prot[key] = prot.get(key, 0) + n
    plan.candidates.sort(key=lambda a: (a.created_at, a.rel))
    return plan


def trash_root(data: Path) -> Path:
    return data / "trash"


def trash_dir(data: Path, prefix: str, now: datetime | None = None) -> Path:
    return trash_root(data) / f"{prefix}-{(now or datetime.now(UTC)).strftime('%Y%m%d')}"


def _move_to_trash(src: Path, dest: Path) -> bool:
    try:
        dest.parent.mkdir(parents=True, exist_ok=True)
        if dest.exists():
            dest = dest.with_name(f"{dest.stem}-{int(time.time())}{dest.suffix}")
        try:
            os.replace(src, dest)
        except OSError:
            shutil.move(str(src), str(dest))
        return True
    except FileNotFoundError:
        return False
    except OSError as e:
        log.warning("could not move %s to the trash: %s", src.name, e)
        return False


def execute_expiry(con: sqlite3.Connection, data_dir: Path | str | None, plan: Plan, *,
                   now: datetime | None = None, batch: int = 200, sleep: float = 0.02,
                   deadline: float | None = None) -> dict[str, Any]:
    """Expire exactly ``plan``'s candidates in bounded batches: record the name in
    ``media_expired`` first, then move the file into the dated trash folder."""
    data = _data(data_dir)
    now = now or datetime.now(UTC)
    tdir = trash_dir(data, "images", now)
    rows = nbytes = 0
    by_kind: dict[str, int] = {}
    for chunk in _chunks(plan.candidates, batch):
        con.execute("BEGIN IMMEDIATE")
        try:
            moved: list[ImageAsset] = []
            for a in chunk:
                con.execute("INSERT OR REPLACE INTO media_expired(name,expired_at,kind) VALUES(?,?,?)",
                            (a.name, _iso(now.timestamp()), a.kind))
                moved.append(a)
            con.execute("COMMIT")
        except Exception:
            con.execute("ROLLBACK")
            raise
        failed: list[str] = []
        for a in moved:
            if _move_to_trash(a.path, tdir / a.rel):
                rows += 1
                nbytes += a.size
                by_kind[a.kind] = by_kind.get(a.kind, 0) + 1
            elif a.path.exists():
                failed.append(a.name)
            # a file that vanished meanwhile: the expired row is still right
        if failed:
            con.executemany("DELETE FROM media_expired WHERE name=?", [(n,) for n in failed])
        if sleep:
            time.sleep(sleep)
        if deadline and time.monotonic() > deadline:
            break
    return {"rows": rows, "bytes": nbytes, "by_kind": by_kind, "trash": str(tdir)}


def restore_images(con: sqlite3.Connection, data_dir: Path | str | None, *, date: str | None = None,
                   names: list[str] | None = None) -> dict[str, int]:
    """Put expired pictures back from ``trash/images-<date>/`` (every dated folder when ``date`` is
    None) and drop their ``media_expired`` rows. ``names`` limits it to those names."""
    data = _data(data_dir)
    want = set(names) if names else None
    restored = skipped = 0
    root = trash_root(data)
    try:
        folders = sorted(d for d in root.iterdir() if d.is_dir() and d.name.startswith("images-")
                         and (date is None or d.name == f"images-{date}"))
    except OSError:
        folders = []
    for folder in folders:
        for e in _walk_files(folder):
            p = Path(e.path)
            rel = p.relative_to(folder).as_posix()
            name = p.name if rel.startswith("media/") else rel
            if want is not None and name not in want:
                continue
            dest = data / rel
            if dest.exists():
                skipped += 1
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            try:
                os.replace(p, dest)
            except OSError:
                shutil.move(str(p), str(dest))
            con.execute("DELETE FROM media_expired WHERE name=?", (name,))
            restored += 1
    return {"restored": restored, "skipped": skipped}


_TRASH_RE = re.compile(r"^(images|orphans)-(\d{8})$")


def purge_trash(data_dir: Path | str | None, *, images_days: int, orphans_days: int,
                now: datetime | None = None) -> dict[str, int]:
    """Delete trash folders older than their hold. Files go in bounded groups."""
    data = _data(data_dir)
    now = now or datetime.now(UTC)
    files = nbytes = 0
    root = trash_root(data)
    try:
        folders = [d for d in root.iterdir() if d.is_dir()]
    except OSError:
        return {"rows": 0, "bytes": 0}
    for d in folders:
        m = _TRASH_RE.match(d.name)
        if not m:
            continue
        try:
            made = datetime.strptime(m.group(2), "%Y%m%d").replace(tzinfo=UTC)
        except ValueError:
            continue
        hold = images_days if m.group(1) == "images" else orphans_days
        if (now - made).days < hold:
            continue
        for e in _walk_files(d):
            with contextlib.suppress(OSError):
                nbytes += e.stat(follow_symlinks=False).st_size
                os.unlink(e.path)
                files += 1
        shutil.rmtree(d, ignore_errors=True)
    return {"rows": files, "bytes": nbytes}


# --------------------------------------------------------------------------- #
# The orphan sweep
# --------------------------------------------------------------------------- #

#: A sweep that would move more than this share of a store (and more than the minimum count) reads
#: as a broken index, not as orphans: it refuses (the file-record sweep in main has the same guard).
ORPHAN_MAX_FRACTION = 0.2
ORPHAN_MIN_RECORDS = 200


def _avatar_roots(names) -> set[str]:
    return {_snapshot_stem(n) for n in names if n}


def find_orphans(con: sqlite3.Connection, data_dir: Path | str | None, *, grace_days: int,
                 now: datetime | None = None) -> dict[str, Any]:
    """Blobs nothing refers to, older than the grace period:

    * ``media/`` files that no message, generated-media record, image-studio row, image job or
      ``files`` row shows (an upload nobody sent, a failed ingest);
    * ``files/`` blobs with no ``files`` row;
    * ``avatars/`` files no bot or profile uses.

    Returns ``{"candidates": [(path, rel, bytes, store)], "refused": {store: reason}, "missing":
    [files rows whose blob is gone]}``. Rows whose blob is missing are reported, never deleted."""
    data = _data(data_dir)
    now = now or datetime.now(UTC)
    cutoff = now.timestamp() - grace_days * 86400
    out: dict[str, Any] = {"candidates": [], "refused": {}, "missing": []}

    def consider(store: str, root: Path, referenced: Callable[[str], bool], images_only: bool) -> None:
        total = 0
        found: list[tuple[Path, str, int]] = []
        for e in _walk_files(root):
            if images_only and not _is_image(e.name):
                continue
            if e.name.startswith(".") or e.name.endswith(".part"):
                continue
            total += 1
            try:
                st = e.stat(follow_symlinks=False)
            except OSError:
                continue
            if st.st_mtime > cutoff:
                continue
            if referenced(e.name):
                continue
            p = Path(e.path)
            found.append((p, _rel(data, p), st.st_size))
        if len(found) > ORPHAN_MIN_RECORDS and len(found) > total * ORPHAN_MAX_FRACTION:
            out["refused"][store] = f"{len(found)} of {total} files look unreferenced: that reads as a gap in the index, not as orphans"
            return
        out["candidates"].extend((p, rel, size, store) for p, rel, size in found)

    # ---- media/: referenced by a message, a generated record, the studio ledger or a file row
    studio = {m.group(1) for r in read_studio_ledger(data) if (m := _MEDIA_REF_RE.search(str(r.get("url") or "")))}
    job_names: set[str] = set()
    try:
        for (url,) in con.execute("SELECT media_url FROM image_jobs WHERE media_url IS NOT NULL"):
            job_names.update(_MEDIA_REF_RE.findall(url))
    except sqlite3.OperationalError:
        pass
    active = _active_job_names(con)

    def media_ok(name: str) -> bool:
        if name in studio or name in job_names or name in active:
            return True
        if con.execute("SELECT 1 FROM media_refs WHERE name=?", (name,)).fetchone():
            return True
        if con.execute("SELECT 1 FROM generated_media WHERE name=?", (name,)).fetchone():
            return True
        if con.execute("SELECT 1 FROM media_expired WHERE name=?", (name,)).fetchone():
            return True
        return False

    consider("media", data / "media", media_ok, images_only=False)

    # ---- files/: a files row names its blob
    try:
        stored = {r[0] for r in con.execute("SELECT stored_name FROM files")}
    except sqlite3.OperationalError:
        stored = set()
    consider("files", data / "files", lambda n: n in stored, images_only=False)
    for name in sorted(stored):
        if name and Path(name).name == name and not (data / "files" / name).exists():
            out["missing"].append(name)
            if len(out["missing"]) >= 200:
                break

    # ---- avatars/: only the data folder's own avatars (never the shipped fallback folder)
    try:
        from . import accounts, config
        used = set()
        for b in config.load_bots():
            used.add(getattr(b, "avatar", "") or "")
        for p in accounts.list_profiles():
            used.add(getattr(p, "avatar", "") or "")
        roots = _avatar_roots(Path(u).name for u in used)
    except Exception:
        out["refused"]["avatars"] = "the roster could not be read"
        roots = None
    if roots is not None:
        consider("avatars", data / "avatars", lambda n: _snapshot_stem(n) in roots, images_only=True)
    return out


def move_orphans(found: dict[str, Any], data_dir: Path | str | None, *, now: datetime | None = None,
                 batch: int = 200, sleep: float = 0.02) -> dict[str, int]:
    data = _data(data_dir)
    now = now or datetime.now(UTC)
    tdir = trash_dir(data, "orphans", now)
    rows = nbytes = 0
    cands = found.get("candidates", [])
    for chunk in _chunks(cands, batch):
        for p, rel, size, _store in chunk:
            if _move_to_trash(p, tdir / rel):
                rows += 1
                nbytes += size
        if sleep:
            time.sleep(sleep)
    return {"rows": rows, "bytes": nbytes}
