def months_ago(now: datetime, months: int) -> datetime:
    """``now`` minus whole calendar months (day clamped to the month's length)."""
    y, m = now.year, now.month - int(months)
    while m <= 0:
        m += 12
        y -= 1
    day = min(now.day, calendar.monthrange(y, m)[1])
    return now.replace(year=y, month=m, day=day)


def _epoch(text: str | None) -> float:
    """An ISO timestamp (naive means UTC) as epoch seconds; 0.0 for anything unreadable."""
    if not text:
        return 0.0
    try:
        d = datetime.fromisoformat(str(text).replace("Z", "+00:00"))
    except ValueError:
        return 0.0
    if d.tzinfo is None:
        d = d.replace(tzinfo=UTC)
    return d.timestamp()


def _iso(epoch: float) -> str:
    return datetime.fromtimestamp(epoch, UTC).isoformat(timespec="seconds")


def _chunks(items: list, n: int) -> Iterator[list]:
    for i in range(0, len(items), n):
        yield items[i:i + n]


def _marks(n: int) -> str:
    return ",".join("?" * n)


def _is_image(name: str) -> bool:
    return Path(name).suffix.lower() in IMAGE_EXTS


def _data(data_dir: Path | str | None) -> Path:
    if data_dir is not None:
        return Path(data_dir)
    from . import config
    return Path(config.DATA_DIR)


def _walk_files(root: Path) -> Iterator[os.DirEntry]:
    """Every regular file under ``root`` (iterative, symlinks not followed)."""
    stack = [root]
    while stack:
        d = stack.pop()
        try:
            with os.scandir(d) as it:
                for e in it:
                    try:
                        if e.is_dir(follow_symlinks=False):
                            stack.append(Path(e.path))
                        elif e.is_file(follow_symlinks=False):
                            yield e
                    except OSError:
                        continue
        except OSError:
            continue


