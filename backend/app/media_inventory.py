PROTECT_SHELF = "unfired_reaction_shelf"
PROTECT_POOL_READY = "avatar_pool_ready"
PROTECT_AVATARS = "current_avatars"
PROTECT_SNAPSHOT = "avatar_snapshot_in_use"

#: The writers found by the sweep. ``covered`` says whether the retention rule expires what it
