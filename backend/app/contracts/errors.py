"""The error catalog: every error the API returns, with a stable code.

``error_catalog.json`` (next to this file) is the data: for each error a ``code``, the
HTTP ``status``, the ``message`` template, a ``fix`` (what the person or program
should do next) and a ``docs`` slug (the anchor in ``docs/errors.md``, generated by
``scripts/gen_contracts.py``). ``patterns`` lists every message string the code base
raises for it, with ``{}`` where a value is interpolated.

The wire shape is *additive*. A response that used to be ``{"detail": "..."}`` is
still exactly that, plus one key::

    {"detail": "Thread not found",
     "error": {"code": "thread_not_found", "message": "Thread not found",
               "fix": "Pick a thread from the list; it may have been deleted.",
               "docs": "thread_not_found"}}

A machine caller (``problem.py``) gets the same ``error`` object inside its RFC 9457
document. The frontend keeps reading ``detail``; programs branch on ``error.code``.

``tests/test_error_catalog.py`` scans the source for every ``HTTPException`` literal and
fails when one is not covered by a pattern here, so the catalog cannot rot.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any

CATALOG_PATH = Path(__file__).with_name("error_catalog.json")
DOCS_BASE = "docs/errors.md#"


@dataclass(frozen=True)
class ErrorSpec:
    code: str
    status: int
    message: str
    fix: str
    docs: str
    patterns: tuple[str, ...] = ()

    def envelope(self, message: str | None = None) -> dict[str, str]:
        return {"code": self.code, "message": message or self.message,
                "fix": self.fix, "docs": self.docs}


@lru_cache(maxsize=1)
def _load() -> tuple[dict[str, ErrorSpec], list[tuple[re.Pattern[str], ErrorSpec]]]:
    raw = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    by_code: dict[str, ErrorSpec] = {}
    matchers: list[tuple[re.Pattern[str], ErrorSpec]] = []
    for e in raw["errors"]:
        spec = ErrorSpec(code=e["code"], status=int(e["status"]), message=e["message"],
                         fix=e["fix"], docs=e.get("docs") or e["code"],
                         patterns=tuple(e.get("patterns") or ()))
        by_code[spec.code] = spec
        for pat in spec.patterns:
            matchers.append((_template_re(pat), spec))
    return by_code, matchers


def _template_re(template: str) -> re.Pattern[str]:
    """``"Unknown bot: {}"`` -> a regex that matches any value in the braces."""
    parts = [re.escape(p) for p in template.strip().split("{}")]
    return re.compile(r"\A\s*" + r"(?s:.*?)".join(parts) + r"\s*\Z", re.IGNORECASE)


def all_errors() -> list[ErrorSpec]:
    return list(_load()[0].values())


def get(code: str) -> ErrorSpec | None:
    return _load()[0].get(code)


def lookup(status: int | None, detail: Any) -> ErrorSpec | None:
    """The catalog entry for a (status, message) pair, or None.

    The message decides; ``status`` only breaks ties (the same words can be raised
    with two statuses in two places)."""
    if not isinstance(detail, str) or not detail.strip():
        return None
    hits = [spec for rx, spec in _load()[1] if rx.match(detail)]
    if not hits:
        return None
    if status is not None:
        for spec in hits:
            if spec.status == status:
                return spec
    return hits[0]


#: Fallback codes by status, for a response whose message is not catalogued.
_BY_STATUS = {
    400: "bad_request", 401: "unauthorized", 403: "forbidden", 404: "not_found", 409: "conflict",
    413: "payload_too_large", 415: "unsupported_media_type", 422: "validation_error",
    429: "rate_limited",
}


def envelope(code: str | None = None, *, status: int | None = None, detail: Any = None,
             message: str | None = None) -> dict[str, str]:
    """The ``error`` object for a response. Never raises: an unknown code degrades to
    the generic per-status entry, then to a bare code."""
    spec = get(code) if code else None
    if spec is None:
        spec = lookup(status, detail)
    if spec is None and status is not None:
        spec = get(_BY_STATUS.get(status, ""))
    if spec is None:
        return {"code": code or (f"http_{status}" if status else "error"),
                "message": message or (detail if isinstance(detail, str) else "Error"),
                "fix": "", "docs": code or ""}
    return spec.envelope(message if message else (detail if isinstance(detail, str) else None))


def catalog_document() -> dict:
    """The JSON-able contract written to ``docs/contracts/errors.json``."""
    return {
        "schema": 1,
        "envelope": {"error": {"code": "string", "message": "string", "fix": "string", "docs": "string"}},
        "errors": [
            {"code": e.code, "status": e.status, "message": e.message, "fix": e.fix,
             "docs": e.docs, "patterns": list(e.patterns)}
            for e in sorted(all_errors(), key=lambda x: x.code)],
    }
