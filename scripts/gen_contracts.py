#!/usr/bin/env python3
"""Generate docs/contracts/ from the code, or check that the committed copy is current.

    python scripts/gen_contracts.py            # (re)write docs/contracts/ and docs/errors.md
    python scripts/gen_contracts.py --check    # exit 1 and print a diff summary if stale

Outputs (all deterministic: sorted keys, LF endings, no timestamps):

    openapi.json                 the FastAPI app's OpenAPI document
    permissions.json             permissions, roles, the role -> permission matrix, machine scopes
    routes.json                  every route and WebSocket action with its declared requirement
    errors.json                  the error catalog (codes, statuses, fixes)
    capabilities.json            the capability registry + the routes no capability claims yet
    manifests/*.schema.json      JSON Schemas of the Connection / Tool plugin / Voice provider /
                                 Character manifests
    ../errors.md                 the error reference (one anchor per code)

CI runs ``--check`` (tests/test_contracts_drift.py does it in a subprocess), so an API,
permission or error change without regenerated contracts fails the build, and a breaking
OpenAPI diff without a version bump fails it harder (see ``breaking_changes``).

The app is imported against a throw-away data directory and with add-on discovery off, so
the result never depends on the machine it runs on.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
CONTRACTS = DOCS / "contracts"


def _isolate() -> tempfile.TemporaryDirectory:
    """Point the app at a scratch data dir BEFORE it is imported."""
    tmp = tempfile.TemporaryDirectory(prefix="dispatch-contracts-")
    os.environ["DISPATCH_DATA_DIR"] = tmp.name
    os.environ.setdefault("DISPATCH_EXTENSIONS", "off")
    os.environ.setdefault("DISPATCH_EXT_BOOT_MARKER", "0")
    os.environ.setdefault("DISPATCH_VOICE_PREWARM", "0")
    os.environ["DISPATCH_ALLOW_OPEN_INSTALL"] = "1"
    sys.path.insert(0, str(ROOT / "backend"))
    return tmp


def _dump(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _http_routes(main) -> list[tuple[str, str]]:
    from fastapi.routing import APIRoute
    out = []
    for r in main.app.routes:
        if isinstance(r, APIRoute):
            for m in sorted(r.methods - {"HEAD", "OPTIONS"}):
                out.append((m, r.path))
    return sorted(set(out), key=lambda t: (t[1], t[0]))


def _requirement(route_policy, method: str, template: str):
    path = template
    for tok in ("{rel:path}", "{path:path}"):
        path = path.replace(tok, "x")
    import re
    path = re.sub(r"\{[^}]+\}", "x", path)
    return route_policy.requirement_for(method, template, path)


def errors_markdown(catalog: dict) -> str:
    lines = [
        "# Error reference",
        "",
        "<!-- Generated by scripts/gen_contracts.py from backend/app/contracts/error_catalog.json."
        " Do not edit by hand. -->",
        "",
        "Every error DisPatch returns carries a stable `error.code`. The HTTP body keeps the",
        "2.x `detail` string and adds the catalogued object:",
        "",
        "```json",
        '{"detail": "Thread not found",',
        ' "error": {"code": "thread_not_found", "message": "Thread not found",',
        '           "fix": "Pick a thread from the list; it may have been deleted.",',
        '           "docs": "thread_not_found"}}',
        "```",
        "",
        "Branch on `error.code`, never on the message. Machine callers additionally receive an",
        "RFC 9457 `application/problem+json` document with the same `error` object.",
        "",
        "| Code | HTTP | What it means |",
        "|---|---|---|",
    ]
    errs = catalog["errors"]
    for e in errs:
        msg = e["message"].replace("|", "\\|").replace("\n", " ")
        lines.append(f"| [`{e['code']}`](#{e['docs']}) | {e['status']} | {msg} |")
    lines.append("")
    for e in errs:
        lines += [f"## {e['code']}", "", f"<a id=\"{e['docs']}\"></a>", "",
                  f"HTTP **{e['status']}** - {e['message']}", "", f"**Fix:** {e['fix']}", ""]
    return "\n".join(lines).rstrip() + "\n"


def build() -> dict[Path, str]:
    """``{absolute path: file text}`` for everything this script owns."""
    from app import main, route_policy
    from app.contracts import capabilities, errors, manifests, permissions

    out: dict[Path, str] = {}
    out[CONTRACTS / "openapi.json"] = _dump(main.app.openapi())
    out[CONTRACTS / "permissions.json"] = _dump(permissions.permissions_document())

    routes = []
    claimed = {(m, p) for c in capabilities.CAPABILITIES for (m, p) in c.http}
    unmapped = []
    for method, path in _http_routes(main):
        req = _requirement(route_policy, method, path)
        routes.append({"method": method, "path": path,
                       "requirement": req.describe() if req is not None else None})
        if (method, path) not in claimed:
            unmapped.append(f"{method} {path}")
    ws = {a: r.describe() for a, r in sorted(route_policy.WS_ACTION_PERMISSIONS.items())}
    out[CONTRACTS / "routes.json"] = _dump({
        "schema": 1, "routes": routes, "websocket_actions": ws,
        "websocket_routes": {p: r.describe() for p, r in sorted(route_policy.WS_ROUTES.items())},
        "mounts": {p: r.describe() for p, r in route_policy.MOUNTS},
    })
    catalog = errors.catalog_document()
    out[CONTRACTS / "errors.json"] = _dump(catalog)
    out[CONTRACTS / "capabilities.json"] = _dump(capabilities.document(sorted(unmapped)))
    for name, doc in manifests.schema_documents().items():
        out[CONTRACTS / "manifests" / f"{name}.schema.json"] = _dump(doc)
    out[DOCS / "errors.md"] = errors_markdown(catalog)
    return out


def breaking_changes(old_openapi: dict, new_openapi: dict) -> list[str]:
    """What a client could notice: a removed path/operation, a removed response code or a
    parameter that became required. Used by CI to demand a major version bump."""
    out = []
    for path, ops in old_openapi.get("paths", {}).items():
        new_ops = new_openapi.get("paths", {}).get(path)
        if new_ops is None:
            out.append(f"removed path {path}")
            continue
        for method, op in ops.items():
            if method not in new_ops:
                out.append(f"removed operation {method.upper()} {path}")
                continue
            old_req = {p["name"] for p in op.get("parameters", []) if p.get("required")}
            new_req = {p["name"] for p in new_ops[method].get("parameters", []) if p.get("required")}
            for name in sorted(new_req - old_req):
                out.append(f"{method.upper()} {path}: parameter {name!r} became required")
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the committed contracts are stale")
    args = ap.parse_args(argv)
    tmp = _isolate()
    try:
        built = build()
    finally:
        pass
    stale = []
    for path, text in sorted(built.items()):
        cur = path.read_text(encoding="utf-8") if path.exists() else None
        if cur == text:
            continue
        if args.check:
            diff = "".join(difflib.unified_diff(
                (cur or "").splitlines(True), text.splitlines(True),
                fromfile=f"committed/{path.relative_to(ROOT)}", tofile="generated", n=1))
            stale.append((path, diff))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT)}")
    tmp.cleanup()
    if args.check:
        if stale:
            for path, diff in stale:
                print(f"STALE {path.relative_to(ROOT)}\n{diff[:2000]}")
            print("\nRun: python scripts/gen_contracts.py   and commit the result.")
            return 1
        print("contracts are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
